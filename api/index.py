# POST /api/purchase-orders/<id>/receive
# Receive stock against a PO — updates received_qty, product stock, inventory_transactions
# Body: { items: [{po_item_id, received_qty}], notes }
# ---------------------------------------------------------------------------

@app.post("/purchase-orders/<int:po_id>/receive")
@app.post("/api/purchase-orders/<int:po_id>/receive")
def receive_purchase_order(po_id: int):
    caller, err_resp = require_auth()
    if err_resp:
        return err_resp

    body  = request.get_json(silent=True) or {}
    items = body.get("items", [])
    notes = (body.get("notes") or "").strip() or None
    received_by = caller.get("username", "unknown")

    if not items:
        return jsonify({"detail": "No items provided"}), 400

    ensure_db()
    conn = get_conn()
    cur  = get_cur(conn)
    try:
        cur.execute("SELECT * FROM purchase_orders WHERE id = %s", (po_id,))
        po = cur.fetchone()
        if not po:
            return jsonify({"detail": "Purchase order not found"}), 404
        if po["status"] == "received":
            return jsonify({"detail": "This purchase order is already fully received"}), 400

        po_number = po["po_number"]

        for item in items:
            poi_id  = item.get("po_item_id")
            recv_qty = float(item.get("received_qty", 0))
            if not poi_id or recv_qty <= 0:
                continue

            cur.execute(
                "SELECT * FROM purchase_order_items WHERE id = %s AND po_id = %s",
                (poi_id, po_id),
            )
            poi = cur.fetchone()
            if not poi:
                continue

            # Update received_qty on the PO item
            new_recv = float(poi["received_qty"]) + recv_qty
            cur.execute(
                "UPDATE purchase_order_items SET received_qty = %s, updated_at = NOW() WHERE id = %s",
                (new_recv, poi_id),
            )

            # Update product stock + mfg/expiry dates + write inventory transaction
            pid = poi["product_id"]
            cur.execute(
                "SELECT current_stock, track_stock FROM products WHERE id = %s",
                (pid,),
            )
            prod = cur.fetchone()
            if prod and prod["track_stock"]:
                stock_before = float(prod["current_stock"] or 0)
                stock_after  = stock_before + recv_qty
                # Propagate mfg/expiry from PO item to product if present
                mfg_date    = poi.get("mfg_date")
                expiry_date = poi.get("expiry_date")
                extra_fields = ""
                if mfg_date:
                    extra_fields += ", mfg_date = %s" % (f"'{mfg_date}'",)
                if expiry_date:
                    extra_fields += ", expiry_date = %s" % (f"'{expiry_date}'",)
                cur.execute(
                    f"UPDATE products SET current_stock = %s{extra_fields}, updated_at = NOW() WHERE id = %s",
                    (stock_after, pid),
                )
                cur.execute(
                    """
                    INSERT INTO inventory_transactions
                      (product_id, transaction_type, quantity_change, stock_before, stock_after,
                       reference_type, reference_id, remarks)
                    VALUES (%s, 'purchase', %s, %s, %s, 'purchase_order', %s, %s)
                    """,
                    (pid, recv_qty, stock_before, stock_after, po_number,
                     f"PO received by {received_by}" + (f": {notes}" if notes else "")),
                )

        # Recompute PO status
        cur.execute(
            "SELECT ordered_qty, received_qty FROM purchase_order_items WHERE po_id = %s",
            (po_id,),
        )
        all_items  = cur.fetchall()
        fully_recv = all(float(r["received_qty"]) >= float(r["ordered_qty"]) for r in all_items)
        any_recv   = any(float(r["received_qty"]) > 0 for r in all_items)
        new_status = "received" if fully_recv else ("partial" if any_recv else "open")
        cur.execute(
            "UPDATE purchase_orders SET status = %s, updated_at = NOW() WHERE id = %s",
            (new_status, po_id),
        )

        conn.commit()

        # Return updated PO
        cur.execute("SELECT * FROM purchase_orders WHERE id = %s", (po_id,))
        po_dict = _po_to_dict(cur.fetchone())
        cur.execute("SELECT * FROM purchase_order_items WHERE po_id = %s ORDER BY id", (po_id,))
        po_dict["items"] = [_po_to_dict(r) for r in cur.fetchall()]
        return jsonify({"message": "Stock received successfully", "purchase_order": po_dict})
    except Exception as e:
        conn.rollback()
        return jsonify({"detail": str(e)}), 400
    finally:
        cur.close(); conn.close()


