def _get_dsn() -> str:
    dsn = os.environ.get("DATABASE_URL", "")
    if not dsn:
        raise RuntimeError("DATABASE_URL not set")
    parsed = urllib.parse.urlparse(dsn)
    params = urllib.parse.parse_qs(parsed.query, keep_blank_values=True)
    params.pop("channel_binding", None)
    new_query = urllib.parse.urlencode({k: v[0] for k, v in params.items()})
    return parsed._replace(query=new_query).geturl()


def get_conn():
    return psycopg2.connect(_get_dsn(), connect_timeout=15)


def get_cur(conn):
    return conn.cursor(cursor_factory=RealDictCursor)


# ---------------------------------------------------------------------------
# DB init — runs once per cold start
# ---------------------------------------------------------------------------

_db_ready = False


def ensure_db():
    global _db_ready
    if _db_ready:
        return
    conn = get_conn()
    try:
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id            BIGINT       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                    username      VARCHAR(100) NOT NULL UNIQUE,
                    password_hash VARCHAR(255) NOT NULL,
                    full_name     VARCHAR(150) NOT NULL,
                    active        BOOLEAN      NOT NULL DEFAULT TRUE,
                    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS roles (
                    id         BIGINT      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                    name       VARCHAR(50) NOT NULL UNIQUE,
                    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS user_roles (
                    user_id BIGINT NOT NULL REFERENCES users(id),
                    role_id BIGINT NOT NULL REFERENCES roles(id),
                    PRIMARY KEY (user_id, role_id)
                )
            """)
            cur.execute("""
                INSERT INTO roles (name) VALUES ('Admin'), ('Cashier')
                ON CONFLICT (name) DO NOTHING
            """)
        conn.commit()
        _db_ready = True
    finally:
        conn.close()


# ---------------------------------------------------------------------------
# JWT helpers
# ---------------------------------------------------------------------------

def _create_token(user_id: int, username: str, role: str) -> str:
    payload = {
        "sub": str(user_id),
        "username": username,
        "role": role,
        "exp": datetime.now(timezone.utc) + timedelta(hours=JWT_EXP_HOURS),
    }
    return jwt.encode(payload, JWT_SECRET, algorithm=JWT_ALGORITHM)


def _decode_token(token: str) -> dict:
    try:
        return jwt.decode(token, JWT_SECRET, algorithms=[JWT_ALGORITHM])
    except jwt.ExpiredSignatureError:
        raise HTTPException(401, "Token has expired")
    except jwt.InvalidTokenError:
        raise HTTPException(401, "Invalid token")


# ---------------------------------------------------------------------------
# Auth dependencies
# ---------------------------------------------------------------------------

def get_current_user(creds: HTTPAuthorizationCredentials = Depends(bearer)) -> dict:
    """Decode token and return payload. Any logged-in user passes."""
    return _decode_token(creds.credentials)


def require_admin(creds: HTTPAuthorizationCredentials = Depends(bearer)) -> dict:
    """Decode token and enforce Admin role."""
    payload = _decode_token(creds.credentials)
    if payload.get("role") != "Admin":
        raise HTTPException(403, "Admin role required")
    return payload


