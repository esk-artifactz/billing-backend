def _credit_invoice_number(cur):
    from datetime import date
    today = date.today().strftime("%Y%m%d")
    cur.execute("SELECT COUNT(*) AS cnt FROM credit_bills WHERE invoice_number LIKE %s", (f"CRD-{today}-%",))
    cnt = int(cur.fetchone()["cnt"]) + 1
    return f"CRD-{today}-{cnt:04d}"


@app.post("/credit-bills")
@app.post("/api/credit-bills")
def create_credit_bill():
    payload, err_resp = require_auth()
    if err_resp:
        return err_resp

    body             = request.get_json(silent=True) or {}
    customer_name    = (body.get("customer_name") or "").strip()
    customer_mobile  = (body.get("customer_mobile") or "").strip()
    items            = body.get("items", [])
    discount_total   = float(body.get("discount_total", 0))
    amount_paid      = float(body.get("amount_paid", 0))
    notes            = (body.get("notes") or "").strip() or None
    cashier_username = payload.get("username", "unknown")

    if not customer_name:
        return jsonify({"detail": "Customer name is required"}), 400
    if not customer_mobile:
        return jsonify({"detail": "Customer mobile number is required"}), 400
    if not items:
        return jsonify({"detail": "Cart is empty"}), 400

    ensure_db()
    conn = get_conn()
    cur  = get_cur(conn)
    try:
        subtotal = 0.0
        enriched = []
        for item in items:
            pid = item.get("product_id") or item.get("id")
            qty = float(item.get("quantity", 1))
            cur.execute("SELECT * FROM products WHERE id = %s", (pid,))
            product = cur.fetchone()
            if not product:
                return jsonify({"detail": f"Product id={pid} not found"}), 400
            unit_price = float(product["selling_price"])
            line_total = round(unit_price * qty, 2)
            subtotal  += unit_price * qty
            enriched.append({
                "product_id":   pid,
                "product_name": product["name"],
                "quantity":     qty,
                "unit_price":   unit_price,
                "line_total":   line_total,
            })

        grand_total  = round(subtotal - discount_total, 2)
        balance_due  = round(grand_total - amount_paid, 2)
        status       = "paid" if balance_due <= 0 else "pending"
        invoice_number = _credit_invoice_number(cur)

        cur.execute(
            """
            INSERT INTO credit_bills
              (customer_name, customer_mobile, invoice_number, cashier_username,
               bill_date, subtotal, discount_total, grand_total,
               amount_paid, balance_due, status, notes)
            VALUES (%s, %s, %s, %s, NOW(), %s, %s, %s, %s, %s, %s, %s)
            RETURNING *
            """,
            (customer_name, customer_mobile, invoice_number, cashier_username,
             round(subtotal, 2), round(discount_total, 2), grand_total,
             round(amount_paid, 2), balance_due, status, notes),
        )
        bill = dict(cur.fetchone())
        bill_id = bill["id"]

        for item in enriched:
            cur.execute(
                """
                INSERT INTO credit_bill_items
                  (credit_bill_id, product_id, product_name, quantity, unit_price, line_total)
                VALUES (%s, %s, %s, %s, %s, %s)
                """,
                (bill_id, item["product_id"], item["product_name"],
                 item["quantity"], item["unit_price"], item["line_total"]),
            )

        conn.commit()
        return jsonify({"message": "Credit bill created", "credit_bill": bill, "invoice_number": invoice_number}), 201
    except Exception as e:
        conn.rollback()
        return jsonify({"detail": str(e)}), 500
    finally:
        cur.close(); conn.close()


