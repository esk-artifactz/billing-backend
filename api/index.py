# Attendance — MONTHLY REPORT  (GET /api/attendance/report?month=YYYY-MM)
# Returns each employee's summary: present, absent, half_day, leave counts.
# Admin only.
# ---------------------------------------------------------------------------

@app.get("/attendance/report")
@app.get("/api/attendance/report")
def attendance_report():
    admin, err_resp = require_admin()
    if err_resp:
        return err_resp

    from datetime import date
    month = request.args.get("month", date.today().strftime("%Y-%m"))   # YYYY-MM
    try:
        year, mon = int(month.split("-")[0]), int(month.split("-")[1])
    except Exception:
        return jsonify({"detail": "month must be YYYY-MM"}), 400

    ensure_db()
    conn = get_conn()
    cur  = get_cur(conn)
    try:
        cur.execute(
            """
            SELECT
                e.id AS employee_id,
                e.emp_code,
                e.full_name,
                e.role,
                e.daily_rate,
                COALESCE(SUM(CASE WHEN a.status = 'present'  THEN 1 ELSE 0 END), 0) AS present_days,
                COALESCE(SUM(CASE WHEN a.status = 'absent'   THEN 1 ELSE 0 END), 0) AS absent_days,
                COALESCE(SUM(CASE WHEN a.status = 'half_day' THEN 1 ELSE 0 END), 0) AS half_days,
                COALESCE(SUM(CASE WHEN a.status = 'leave'    THEN 1 ELSE 0 END), 0) AS leave_days
            FROM employees e
            LEFT JOIN attendance a
                   ON a.employee_id = e.id
                  AND EXTRACT(YEAR  FROM a.att_date) = %s
                  AND EXTRACT(MONTH FROM a.att_date) = %s
            WHERE e.active = TRUE
            GROUP BY e.id, e.emp_code, e.full_name, e.role, e.daily_rate
            ORDER BY e.full_name
            """,
            (year, mon),
        )
        report = []
        for r in cur.fetchall():
            present    = int(r["present_days"])
            half       = int(r["half_days"])
            leave      = int(r["leave_days"])
            daily_rate = float(r["daily_rate"])
            # effective days: present=1, half_day=0.5, leave=1 (paid leave), absent=0
            effective  = present + half * 0.5 + leave
            earned     = round(daily_rate * effective, 2)
            report.append({
                "employee_id":  r["employee_id"],
                "emp_code":     r["emp_code"],
                "full_name":    r["full_name"],
                "role":         r["role"],
                "daily_rate":   daily_rate,
                "present_days": present,
                "absent_days":  int(r["absent_days"]),
                "half_days":    half,
                "leave_days":   leave,
                "effective_days": effective,
                "gross_earned": earned,
            })

        # Total salary paid this month per employee (sum of all payments)
        cur.execute(
            """
            SELECT employee_id,
                   COALESCE(SUM(amount_paid), 0) AS total_paid
            FROM salary_payments
            WHERE pay_month = %s
            GROUP BY employee_id
            """,
            (month,),
        )
        paid_map = {row["employee_id"]: float(row["total_paid"]) for row in cur.fetchall()}

        # Total advances given this month (not yet recovered)
        cur.execute(
            """
            SELECT employee_id,
                   COALESCE(SUM(amount), 0) AS total_advance
            FROM advances
            WHERE TO_CHAR(given_on, 'YYYY-MM') = %s
              AND recovered = FALSE
            GROUP BY employee_id
            """,
            (month,),
        )
        advance_map = {row["employee_id"]: float(row["total_advance"]) for row in cur.fetchall()}

        for row in report:
            eid        = row["employee_id"]
            paid       = paid_map.get(eid, 0)
            adv        = advance_map.get(eid, 0)
            balance    = round(row["gross_earned"] - paid - adv, 2)
            row["total_paid"]     = paid
            row["total_advance"]  = adv
            row["balance_due"]    = balance

        return jsonify({"report": report, "month": month})
    finally:
        cur.close(); conn.close()


