def _credit_invoice_number(cur):
    from datetime import date
    today = date.today().strftime("%Y%m%d")
    cur.execute("SELECT COUNT(*) AS cnt FROM credit_bills WHERE invoice_number LIKE %s", (f"CRD-{today}-%",))
    cnt = int(cur.fetchone()["cnt"]) + 1
    return f"CRD-{today}-{cnt:04d}"


