# ===========================================================================

@app.get("/expense-report")
@app.get("/api/expense-report")
def expense_report():
    _p, err_resp = require_auth()
    if err_resp:
        return err_resp

    date_from    = request.args.get("from")
    date_to      = request.args.get("to")
    cat_filter   = request.args.get("category")
    mode_filter  = request.args.get("payment_mode")

    ensure_db()
    conn = get_conn(); cur = get_cur(conn)
    try:
        where, vals = ["1=1"], []
        if date_from: where.append("expense_date >= %s"); vals.append(date_from)
        if date_to:   where.append("expense_date <= %s"); vals.append(date_to)
        if cat_filter and cat_filter != "all":
            where.append("category = %s"); vals.append(cat_filter)
        if mode_filter and mode_filter != "all":
            where.append("payment_mode = %s"); vals.append(mode_filter)

        w = " AND ".join(where)

        # Grand total
        cur.execute(f"SELECT COALESCE(SUM(amount),0) AS total FROM daily_expenses WHERE {w}", vals)
        grand_total = float(cur.fetchone()["total"])

        # By category (with color from expense_categories)
        cur.execute(f"""
            SELECT e.category,
                   COALESCE(ec.color, '#d4a017') AS color,
                   COUNT(*)                       AS count,
                   SUM(e.amount)                  AS total
            FROM daily_expenses e
            LEFT JOIN expense_categories ec ON ec.name = e.category
            WHERE {w}
            GROUP BY e.category, ec.color
            ORDER BY total DESC
        """, vals)
        by_category = []
        for r in cur.fetchall():
            by_category.append({
                "category": r["category"],
                "color":    r["color"],
                "count":    int(r["count"]),
                "total":    float(r["total"]),
                "pct":      round(float(r["total"]) / grand_total * 100, 1) if grand_total else 0,
            })

        # By supplier (paid_to) — top spends
        cur.execute(f"""
            SELECT paid_to,
                   COUNT(*)    AS count,
                   SUM(amount) AS total
            FROM daily_expenses
            WHERE {w}
              AND paid_to IS NOT NULL AND paid_to <> ''
            GROUP BY paid_to
            ORDER BY total DESC
            LIMIT 30
        """, vals)
        by_supplier = [
            {"paid_to": r["paid_to"], "count": int(r["count"]), "total": float(r["total"])}
            for r in cur.fetchall()
        ]

        # By payment mode
        cur.execute(f"""
            SELECT payment_mode,
                   COUNT(*)    AS count,
                   SUM(amount) AS total
            FROM daily_expenses
            WHERE {w}
            GROUP BY payment_mode
            ORDER BY total DESC
        """, vals)
        by_mode = [
            {"mode": r["payment_mode"], "count": int(r["count"]), "total": float(r["total"])}
            for r in cur.fetchall()
        ]

        # Daily trend (total per day)
        cur.execute(f"""
            SELECT expense_date,
                   SUM(amount)  AS total,
                   COUNT(*)     AS count
            FROM daily_expenses
            WHERE {w}
            GROUP BY expense_date
            ORDER BY expense_date
        """, vals)
        daily_trend = [
            {"date": r["expense_date"].isoformat(), "total": float(r["total"]), "count": int(r["count"])}
            for r in cur.fetchall()
        ]

        # Recent transactions (last 50 matching the filters)
        cur.execute(f"""
            SELECT * FROM daily_expenses
            WHERE {w}
            ORDER BY expense_date DESC, created_at DESC
            LIMIT 50
        """, vals)
        recent = [_expense_to_dict(r) for r in cur.fetchall()]

        return jsonify({
            "grand_total": grand_total,
            "by_category": by_category,
            "by_supplier": by_supplier,
            "by_mode":     by_mode,
            "daily_trend": daily_trend,
            "recent":      recent,
            "filters": {
                "from": date_from, "to": date_to,
                "category": cat_filter, "payment_mode": mode_filter,
            },
        })
    finally:
        cur.close(); conn.close()


