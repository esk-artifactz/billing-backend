def _product_to_dict(row: dict) -> dict:
    """Return a safe product dict. Booleans must be checked before numeric types."""
    d = dict(row)
    for k, v in d.items():
        if isinstance(v, datetime):
            d[k] = v.isoformat()
        elif isinstance(v, bool):
            d[k] = bool(v)          # keep True/False, do NOT cast to float
        elif isinstance(v, float):
            d[k] = float(v)
    return d


def _user_to_dict(row: dict) -> dict:
    d = dict(row)
    d.pop("password_hash", None)
    for k, v in d.items():
        if isinstance(v, datetime):
            d[k] = v.isoformat()
    return d


def _get_user_role(cur, user_id) -> str | None:
    cur.execute(
        """
        SELECT r.name FROM roles r
        JOIN user_roles ur ON ur.role_id = r.id
        WHERE ur.user_id = %s LIMIT 1
        """,
        (user_id,),
    )
    row = cur.fetchone()
    return row["name"] if row else None


def _assign_role(cur, user_id, role_name: str):
    cur.execute("SELECT id FROM roles WHERE name = %s", (role_name,))
    role = cur.fetchone()
    if not role:
        raise ValueError(f"Role '{role_name}' does not exist. Valid: {VALID_ROLES}")
    cur.execute("DELETE FROM user_roles WHERE user_id = %s", (user_id,))
    cur.execute(
        "INSERT INTO user_roles (user_id, role_id) VALUES (%s, %s)",
        (user_id, role["id"]),
    )


def _verify_password(plain: str, hashed: str) -> bool:
    if hashed.startswith(("scrypt:", "pbkdf2:", "sha256$")):
        return werkzeug_check(hashed, plain)
    return pwd_context.verify(plain, hashed)


def _needs_rehash(hashed: str) -> bool:
    return hashed.startswith(("scrypt:", "pbkdf2:", "sha256$"))


