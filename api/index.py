def _create_token(user_id: int, username: str, role: str) -> str:
    payload = {
        "sub": str(user_id),
        "username": username,
        "role": role,
        "exp": datetime.now(timezone.utc) + timedelta(hours=JWT_EXP_HOURS),
    }
    return jwt.encode(payload, JWT_SECRET, algorithm=JWT_ALGORITHM)


def _decode_token(token: str) -> dict:
    try:
        return jwt.decode(token, JWT_SECRET, algorithms=[JWT_ALGORITHM])
    except jwt.ExpiredSignatureError:
        return None, "Token has expired"
    except jwt.InvalidTokenError:
        return None, "Invalid token"


# ---------------------------------------------------------------------------
# Auth middleware helpers
# ---------------------------------------------------------------------------

def _get_token_from_request():
    auth = request.headers.get("Authorization", "")
    if not auth.startswith("Bearer "):
        return None, "Missing or invalid Authorization header"
    token = auth.split(" ", 1)[1]
    result = _decode_token(token)
    if isinstance(result, tuple):
        return None, result[1]
    return result, None


def require_auth():
    payload, err = _get_token_from_request()
    if err:
        return None, (jsonify({"detail": err}), 401)
    return payload, None


def require_admin():
    payload, err_resp = require_auth()
    if err_resp:
        return None, err_resp
    if payload.get("role") != "Admin":
        return None, (jsonify({"detail": "Admin role required"}), 403)
    return payload, None


