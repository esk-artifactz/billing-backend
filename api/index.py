def _row_to_dict(row):
    """Convert DB row to dict. Booleans checked before numeric to avoid True→1.0."""
    d = dict(row)
    for k, v in d.items():
        if isinstance(v, datetime):
            d[k] = v.isoformat()
        elif isinstance(v, bool):
            d[k] = bool(v)          # keep True/False, do NOT cast to float
        elif hasattr(v, '__float__'):
            d[k] = float(v)
    return d


def _generate_invoice_number(cur):
    """Generate invoice number like INV-20260916-0001."""
    from datetime import date
    today = date.today().strftime("%Y%m%d")
    cur.execute(
        "SELECT COUNT(*) as cnt FROM sales WHERE invoice_number LIKE %s",
        (f"INV-{today}-%",)
    )
    row = cur.fetchone()
    seq = int(row["cnt"]) + 1
    return f"INV-{today}-{seq:04d}"


def _generate_hold_reference(cur):
    """Generate hold reference like HOLD-20260916-001."""
    from datetime import date
    today = date.today().strftime("%Y%m%d")
    cur.execute(
        "SELECT COUNT(*) as cnt FROM held_sales WHERE hold_reference LIKE %s",
        (f"HOLD-{today}-%",)
    )
    row = cur.fetchone()
    seq = int(row["cnt"]) + 1
    return f"HOLD-{today}-{seq:03d}"


