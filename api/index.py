def _emp_to_dict(row: dict) -> dict:
    d = dict(row)
    for k, v in d.items():
        if isinstance(v, datetime):
            d[k] = v.isoformat()
        elif hasattr(v, 'isoformat'):       # date objects
            d[k] = v.isoformat()
        elif isinstance(v, bool):
            d[k] = bool(v)
        elif isinstance(v, float):
            d[k] = float(v)
    return d


