@app.post("/login")
@app.post("/api/login")
def login():
    body = request.get_json(force=True, silent=True)
    if not body:
        import json
        try:
            body = json.loads(request.data.decode("utf-8"))
        except Exception:
            body = {}
    username = (body.get("username") or "").strip()
    password = (body.get("password") or "").strip()

    if not username or not password:
        return jsonify({"detail": "username and password are required"}), 400

    ensure_db()
    conn = get_conn()
    cur  = get_cur(conn)
    try:
        cur.execute("SELECT * FROM users WHERE username = %s", (username,))
        user = cur.fetchone()

        if not user or not _verify_password(password, user["password_hash"]):
            return jsonify({"detail": "Invalid username or password"}), 401
        if not user["active"]:
            return jsonify({"detail": "Account is disabled"}), 403

        # Migrate legacy Werkzeug hash → bcrypt on first successful login
        if _needs_rehash(user["password_hash"]):
            cur.execute(
                "UPDATE users SET password_hash = %s WHERE id = %s",
                (pwd_context.hash(password), user["id"]),
            )
            conn.commit()

        role      = _get_user_role(cur, user["id"])
        token     = _create_token(user["id"], user["username"], role)
        user_data = _user_to_dict(user)
        user_data["role"] = role

        return jsonify({
            "message":    "Login successful",
            "token":      token,
            "token_type": "bearer",
            "user":       user_data,
        })
    finally:
        cur.close(); conn.close()


