@app.post("/api/login")
def login(body: LoginRequest):
    """
    Authenticate user and return a JWT token with role.

    Request:
        { "username": "...", "password": "..." }

    Response:
        {
          "message": "Login successful",
          "token": "<jwt>",
          "token_type": "bearer",
          "user": { "id", "username", "full_name", "role", "active", ... }
        }
    """
    ensure_db()
    username = body.username.strip()
    password = body.password.strip()

    if not username or not password:
        raise HTTPException(400, "username and password are required")

    conn = get_conn()
    cur  = get_cur(conn)
    try:
        cur.execute("SELECT * FROM users WHERE username = %s", (username,))
        user = cur.fetchone()

        if not user or not _verify_password(password, user["password_hash"]):
            raise HTTPException(401, "Invalid username or password")
        if not user["active"]:
            raise HTTPException(403, "Account is disabled")

        # Migrate legacy Werkzeug hash → bcrypt on first successful login
        if _needs_rehash(user["password_hash"]):
            cur.execute(
                "UPDATE users SET password_hash = %s WHERE id = %s",
                (pwd_context.hash(password), user["id"]),
            )
            conn.commit()

        role      = _get_user_role(cur, user["id"])
        token     = _create_token(user["id"], user["username"], role)
        user_data = _user_to_dict(user)
        user_data["role"] = role

        return {
            "message":    "Login successful",
            "token":      token,
            "token_type": "bearer",
            "user":       user_data,
        }
    finally:
        cur.close(); conn.close()


