    amount_tendered  = body.get("amount_tendered")
    customer_name    = (body.get("customer_name") or "").strip() or None
    customer_mobile  = (body.get("customer_mobile") or "").strip() or None
    cashier_username = payload.get("username", "unknown")

    if not items:
        return jsonify({"detail": "Cart is empty"}), 400

    ensure_db()
    conn = get_conn()
    cur  = get_cur(conn)
    try:
        # Validate products and compute totals
        subtotal  = 0.0
        tax_total = 0.0
        enriched  = []
        for item in items:
            pid = item.get("product_id") or item.get("id")
            qty = float(item.get("quantity", 1))
            cur.execute("SELECT * FROM products WHERE id = %s AND active = TRUE", (pid,))
            product = cur.fetchone()
            if not product:
                return jsonify({"detail": f"Product id={pid} not found or inactive"}), 400

            unit_price      = float(product["selling_price"])
            gst_pct         = float(product["gst_percentage"])
            discount_amount = float(item.get("discount_amount", 0))
            tax_amount      = round((unit_price * qty - discount_amount) * gst_pct / 100, 2)
            line_total      = round(unit_price * qty - discount_amount + tax_amount, 2)
            subtotal  += unit_price * qty
            tax_total += tax_amount
            enriched.append({
                "product_id":      pid,
                "product_name":    product["name"],
                "barcode":         product["barcode"],
                "quantity":        qty,
                "unit_price":      unit_price,
                "discount_amount": discount_amount,
                "tax_amount":      tax_amount,
                "line_total":      line_total,
                "track_stock":     product.get("track_stock", True),   # default True if column missing
                "current_stock":   product.get("current_stock"),
            })

        grand_before_round = subtotal - discount_total + tax_total
        grand_total        = round(grand_before_round)
        round_off          = round(grand_total - grand_before_round, 2)
        change_amount      = round(float(amount_tendered or grand_total) - grand_total, 2) if amount_tendered else 0.0

        invoice_number = _generate_invoice_number(cur)

        # Insert sale — sale_time + optional customer fields
        cur.execute(
            """
            INSERT INTO sales (invoice_number, cashier_username, sale_time, subtotal, discount_total, tax_total,
                               round_off, grand_total, payment_method, amount_tendered, change_amount,
                               customer_name, customer_mobile, status)
            VALUES (%s, %s, NOW(), %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, 'completed')
            RETURNING *
            """,
            (invoice_number, cashier_username, round(subtotal, 2), round(discount_total, 2),
             round(tax_total, 2), round_off, grand_total, payment_method,
             float(amount_tendered) if amount_tendered else None, change_amount,
             customer_name, customer_mobile),
        )
        sale = cur.fetchone()
        sale_id = sale["id"]

        # Insert sale items + deduct stock
        for item in enriched:
            cur.execute(
                """
                INSERT INTO sale_items (sale_id, product_id, product_name, barcode, quantity, unit_price, discount_amount, tax_amount, line_total)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (sale_id, item["product_id"], item["product_name"], item["barcode"],
                 item["quantity"], item["unit_price"], item["discount_amount"],
                 item["tax_amount"], item["line_total"]),
            )
            # Only deduct stock for products where track_stock = TRUE
            # Non-stockable items (Tea, Coffee, Juice, etc.) are skipped entirely
            if item.get("track_stock", True) is True and item.get("current_stock") is not None:
                stock_before = float(item["current_stock"])
                stock_after  = max(0.0, stock_before - item["quantity"])
                cur.execute(
                    "UPDATE products SET current_stock = %s, updated_at = NOW() WHERE id = %s",
                    (stock_after, item["product_id"]),
                )
                cur.execute(
                    """
                    INSERT INTO inventory_transactions (product_id, transaction_type, quantity_change, stock_before, stock_after, reference_type, reference_id, remarks)
                    VALUES (%s, 'sale', %s, %s, %s, 'sale', %s, %s)
                    """,
                    (item["product_id"], -item["quantity"], stock_before, stock_after,
                     invoice_number, f"Sale: {invoice_number}"),
                )
            # If track_stock = FALSE → skip stock update and inventory log entirely

        conn.commit()
        return jsonify({
            "message":        "Sale completed successfully",
            "invoice_number": invoice_number,
            "sale_id":        sale_id,
            "grand_total":    grand_total,
            "change_amount":  change_amount,
            "sale":           _row_to_dict(sale),
        }), 201

    except Exception as e:
        conn.rollback()
        return jsonify({"detail": str(e)}), 400
    finally:
        cur.close(); conn.close()


